-- Backend-owned settings (e.g. the symmetric-key part used to protect
-- secrets, or the cron quiet-hours window), kept in a table of its own
-- instead of alongside user-editable configurations. There is no value_type
-- column: the jsonb value already carries its own shape, and the frontend
-- picks a dedicated form per entry by name. value_hidden decides whether the
-- API ever returns the value at all - it defaults to true (fail-safe: a
-- future entry is secret-shaped until explicitly marked otherwise) and is
-- fixed per row at seed time, never editable through the API.
CREATE TABLE core.system_configurations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    version bigint NOT NULL DEFAULT 0,
    name text NOT NULL,
    value jsonb NOT NULL,
    value_hidden boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT pk_system_configurations PRIMARY KEY (id),
    CONSTRAINT uq_system_configurations_name UNIQUE (name),
    CONSTRAINT ck_system_configurations_name_trimmed CHECK (name = btrim(name) AND name <> ''),
    CONSTRAINT ck_system_configurations_value_not_null CHECK (value <> 'null'::jsonb)
);

CREATE UNIQUE INDEX uq_system_configurations_name_ci ON core.system_configurations (lower(name));

