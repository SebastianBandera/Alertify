CREATE TABLE core.tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    version bigint NOT NULL DEFAULT 0,
    scope varchar(32) NOT NULL,
    name text NOT NULL,
    color varchar(7) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT pk_tags PRIMARY KEY (id),
    CONSTRAINT uq_tags_scope_name UNIQUE (scope, name),
    CONSTRAINT uq_tags_id_scope UNIQUE (id, scope),
    CONSTRAINT ck_tags_scope CHECK (scope IN ('CONFIGURATION', 'SECRET')),
    CONSTRAINT ck_tags_name_trimmed CHECK (name = btrim(name) AND name <> ''),
    CONSTRAINT ck_tags_color CHECK (color ~ '^#[0-9A-F]{6}$')
);

CREATE UNIQUE INDEX uq_tags_scope_name_ci ON core.tags (scope, lower(name));

CREATE TABLE core.configuration_tag (
    configuration_id bigint NOT NULL,
    tag_id bigint NOT NULL,
    tag_scope varchar(32) NOT NULL DEFAULT 'CONFIGURATION',
    CONSTRAINT pk_configuration_tag PRIMARY KEY (configuration_id, tag_id),
    CONSTRAINT ck_configuration_tag_scope CHECK (tag_scope = 'CONFIGURATION'),
    CONSTRAINT fk_configuration_tag_configuration
        FOREIGN KEY (configuration_id) REFERENCES core.configurations (id) ON DELETE CASCADE,
    CONSTRAINT fk_configuration_tag_tag_scope
        FOREIGN KEY (tag_id, tag_scope) REFERENCES core.tags (id, scope) ON DELETE RESTRICT
);

CREATE INDEX idx_configuration_tag_tag ON core.configuration_tag (tag_id, configuration_id);

CREATE TABLE core.configuration_expression_dependencies (
    configuration_id bigint NOT NULL,
    referenced_configuration_id bigint NOT NULL,
    CONSTRAINT pk_configuration_expression_dependencies PRIMARY KEY (
        configuration_id, referenced_configuration_id
    ),
    CONSTRAINT fk_configuration_expression_dependencies_configuration
        FOREIGN KEY (configuration_id) REFERENCES core.configurations (id) ON DELETE CASCADE,
    CONSTRAINT fk_configuration_expression_dependencies_referenced_configuration
        FOREIGN KEY (referenced_configuration_id) REFERENCES core.configurations (id) ON DELETE RESTRICT
);

CREATE INDEX idx_configuration_expression_dependencies_referenced
    ON core.configuration_expression_dependencies (referenced_configuration_id, configuration_id);

